<?php

	/*
	 * Запуск службы в текущем процессе.
	 *
	 * 	./console service run <name> [args...] [--force]
	 *
	 * Всё без '--' уходит службе в $argv; '--force' видит и она,
	 * а фасад трактует его для себя (обход сторожка «один инстанс»).
	 * Файл ничего не печатает: вывод службы журналирует фасад
	 * (канал service.<name>), stdout под демоном глушится сам.
	 */

	$name = array_shift($args);
	if (!$name) throw new Exception("Использование: console service run <name> [args] [--force]");

	//Служба — «чужая программа»: её контракт — сырой $argv, а не каналы
	//диспетчера. Собираем токены обратно: k=v из $vars и --flag/--k=v
	//из $flags — всё, как было в команде ('--force' служба тоже увидит;
	//фасад трактует его для себя параллельно).
	//Порядок токенов внутри канала сохранён, между каналами разбор
	//теряет — vars/flags уходят в хвост argv (служба парсит семантику,
	//не позицию).
	foreach ($vars  as $k => $v) $args[] = "$k=$v";
	foreach ($flags as $k => $v) $args[] = $v === true ? "--$k" : "--$k=$v";

	$APP->service->run($name, $args, ['force' => !empty($flags['force'])]);
